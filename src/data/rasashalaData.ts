export interface NernstGridParams {
  nSeries: number;
  nParallel: number;
  cellCapacityAh: number;
  compostTempCelsius: number;
  concentrationRatio: number; // [Zn2+] / [Cu2+]
}

export function calculateNernstAgastyaDynamics(params: NernstGridParams) {
  const R = 8.314; // J/(mol*K)
  const F = 96485; // C/mol
  const n = 2; // Electrons exchanged
  const E0 = 1.10; // Standard potential in Volts
  const T = params.compostTempCelsius + 273.15; // Kelvin

  // Nernst Equation: E_cell = E0 - (RT/nF) * ln(Q)
  const nernstCorrection = ((R * T) / (n * F)) * Math.log(params.concentrationRatio);
  const eCell = E0 - nernstCorrection;

  const totalVoltage = params.nSeries * eCell;
  const totalCapacityAh = params.nParallel * params.cellCapacityAh;
  const totalEnergyKwh = (totalVoltage * totalCapacityAh) / 1000.0;

  const thermalGainPercent = (((eCell - E0) / E0) * 100);

  return {
    eCell: Math.round(eCell * 1000) / 1000,
    totalVoltage: Math.round(totalVoltage * 100) / 100,
    totalCapacityAh: Math.round(totalCapacityAh * 100) / 100,
    totalEnergyKwh: Math.round(totalEnergyKwh * 100) / 100,
    nernstCorrectionMv: Math.round(nernstCorrection * 1000 * 10) / 10,
    thermalGainPercent: Math.round(thermalGainPercent * 10) / 10,
    kelvinTemp: Math.round(T * 10) / 10,
    totalCells: params.nSeries * params.nParallel,
  };
}

export function calculateAgastyaOutput(params: AgastyaGridParams) {
  // Backwards compatible wrapper leveraging Nernst dynamics
  const nernst = calculateNernstAgastyaDynamics({
    nSeries: 50,
    nParallel: Math.max(1, Math.round(params.cellCount / 50)),
    cellCapacityAh: params.capacityAh / 2,
    compostTempCelsius: 55.0,
    concentrationRatio: 0.05,
  });

  const dailyBiogasFromPotsM3 = 0.35 * (params.dungMassKg + params.compostMassKg);

  return {
    voltagePerCell: nernst.eCell,
    totalVoltage: nernst.totalVoltage,
    totalEnergyKwh: nernst.totalEnergyKwh,
    dailyBiogasFromPotsM3,
    gridType: 'Underground Organic Electrochemical Storage',
    thermalFeedback: 'Active Compost Heat at 55.0°C (Thermodynamic Nernst Boost)',
    substrateEfficiency: Math.min(99, Math.round(85 + (params.compostMassKg / (params.dungMassKg + params.compostMassKg)) * 20)),
    nernstGain: nernst.thermalGainPercent,
  };
}

export function calculateBiogasPower(params: BiogasParams) {
  // 1 m3 of biogas with 60% methane yields ~2.14 kWh electricity
  const methaneRatio = params.methanePercentage / 100.0;
  const energyDensityPerM3 = 2.14 * (methaneRatio / 0.60);
  const totalDailyKwh = params.digesterVolumeM3 * energyDensityPerM3 * (params.generatorEfficiency / 0.30);
  const thermalCoGenKw = params.digesterVolumeM3 * 2.8;

  // Real-time Digester Pressure in mbar (Nominal 20-35 mbar, Overpressure >45 mbar)
  const basePressureMbar = Math.round(18 + (params.digesterVolumeM3 / 120) * 8 + (params.methanePercentage - 60) * 0.4);

  return {
    methaneRatio,
    energyDensityPerM3,
    totalDailyKwh: Math.round(totalDailyKwh * 10) / 10,
    thermalCoGenKw: Math.round(thermalCoGenKw * 10) / 10,
    basePressureMbar,
    furnaceHeatRedirect: 'Active (Redirected to Agneya Induction Furnaces)',
    carbonOffsetKgDay: Math.round(totalDailyKwh * 0.82),
  };
}

export interface ClusterOrchestratorState {
  activeNodes: number;
  totalNodes: number;
  mode: 'surge' | 'steady' | 'conserve';
  status: string;
  biogasKwh: number;
  agastyaSoc: number;
}

export function evaluateClusterLoad(biogasKwh: number, agastyaSoc: number, totalNodes = 128): ClusterOrchestratorState {
  if (biogasKwh > 35.0 && agastyaSoc > 75.0) {
    return {
      activeNodes: totalNodes,
      totalNodes,
      mode: 'surge',
      status: 'ENERGY SURGE: Firing up all nodes. Running massive parallel Chiral Lattice simulations.',
      biogasKwh,
      agastyaSoc,
    };
  } else if (biogasKwh >= 20.0 || agastyaSoc >= 50.0) {
    return {
      activeNodes: Math.round(totalNodes * 0.6),
      totalNodes,
      mode: 'steady',
      status: 'SUSTAINED STEADY GRID: Running baseline molecular docking matrices.',
      biogasKwh,
      agastyaSoc,
    };
  } else {
    return {
      activeNodes: Math.max(8, Math.round(totalNodes * 0.1)),
      totalNodes,
      mode: 'conserve',
      status: 'EMERGENCY POWER CONSERVATION: Shifting compute workloads to offline queue. Hibernating nodes.',
      biogasKwh,
      agastyaSoc,
    };
  }
}

