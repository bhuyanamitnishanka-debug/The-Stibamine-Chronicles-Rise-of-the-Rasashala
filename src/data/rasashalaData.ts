export function calculateSynthesisYield(
  furnaceTempC: number,
  vacuumLevelMbar: number,
  chiralSeedAdded: boolean,
  herbalExtractMl: number
) {
  // Ideal conditions: temp 750-820C, vacuum < 15 mbar, herbal extract 40-60 ml, chiral seeded
  const tempFactor = Math.max(0, 1 - Math.abs(furnaceTempC - 780) / 400);
  const vacuumFactor = Math.max(0, 1 - Math.max(0, vacuumLevelMbar - 10) / 50);
  const herbalFactor = Math.min(1, herbalExtractMl / 50);

  const basePurity = 60 * tempFactor + 25 * vacuumFactor + 15 * herbalFactor;
  const enantiomerPurity = chiralSeedAdded ? Math.min(99.8, Math.max(88, basePurity * 0.99)) : Math.min(65, basePurity * 0.6);

  const parasiteMortality = Math.min(99.9, Math.round((enantiomerPurity * 0.98 + (chiralSeedAdded ? 2 : 0)) * 10) / 10);
  // Liver cytotoxicity score (lower is safer)
  const liverCytotoxicity = Math.max(1.2, Math.round((100 - enantiomerPurity * 0.95) * 10) / 10);

  return {
    enantiomerPurity: Math.round(enantiomerPurity * 10) / 10,
    parasiteMortality,
    liverCytotoxicity,
    isSafeForHumanTrials: enantiomerPurity > 95 && liverCytotoxicity < 10,
    crystalStructure: chiralSeedAdded
      ? 'Uniform Rhombohedral Chiral Lattice (Urea Stibamine Pure)'
      : 'Racemic Amorphous Mixture (High Liver Toxicity)',
  };
}
